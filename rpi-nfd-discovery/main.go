package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

var safeValue = regexp.MustCompile(`[^a-z0-9.-]+`)

func readModel(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	model := strings.TrimSpace(strings.TrimRight(string(data), "\x00"))
	if !strings.HasPrefix(model, "Raspberry Pi ") {
		return "", fmt.Errorf("not a Raspberry Pi: %q", model)
	}
	return model, nil
}

func modelID(model string) string {
	name := strings.TrimPrefix(model, "Raspberry Pi ")
	name = strings.TrimSpace(strings.Split(name, " Rev ")[0])
	name = strings.ToLower(name)
	name = strings.ReplaceAll(name, " Model ", " ")
	name = strings.ReplaceAll(name, " Plus", "+")
	name = strings.ReplaceAll(name, "+", "plus")
	name = strings.ReplaceAll(name, " ", "-")
	return strings.Trim(safeValue.ReplaceAllString(name, "-"), "-.")
}

func revision(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(data), "\n") {
		if key, val, ok := strings.Cut(line, ":"); ok && strings.TrimSpace(key) == "Revision" {
			value := strings.ToLower(strings.TrimSpace(val))
			if regexp.MustCompile(`^[a-f0-9]+$`).MatchString(value) {
				return value
			}
		}
	}
	return ""
}

func featureContent(model, rev string) string {
	var b strings.Builder
	fmt.Fprintln(&b, "# Automatically generated by rpi-nfd-discovery")
	fmt.Fprintln(&b, "feature.node.kubernetes.io/rpi-present=true")
	fmt.Fprintf(&b, "feature.node.kubernetes.io/rpi-model=%s\n", modelID(model))
	if rev != "" {
		fmt.Fprintf(&b, "feature.node.kubernetes.io/rpi-revision=%s\n", rev)
	}
	return b.String()
}

func writeAtomic(path, data string) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".rpi-nfd-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.WriteString(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

func main() {
	modelPath := flag.String("model", "/host/device-tree/model", "host device-tree model file")
	cpuInfoPath := flag.String("cpuinfo", "/host/cpuinfo", "host /proc/cpuinfo")
	output := flag.String("output", "/features.d/rpi", "NFD local feature file")
	interval := flag.Duration("interval", 5*time.Minute, "reconciliation interval")
	flag.Parse()

	if *interval <= 0 {
		log.Fatal("interval must be positive")
	}
	for {
		model, err := readModel(*modelPath)
		if err != nil {
			log.Printf("discovery failed: %v", err)
		} else {
			content := featureContent(model, revision(*cpuInfoPath))
			old, err := os.ReadFile(*output)
			if err != nil || string(old) != content {
				if err := writeAtomic(*output, content); err != nil {
					log.Printf("feature write failed: %v", err)
				} else {
					log.Printf("discovered %s (%s)", model, modelID(model))
				}
			}
		}
		time.Sleep(*interval)
	}
}
